package gotun

import (
	"fmt"
	"gopkg.in/yaml.v3"
	"os"
	"path"
)

type AppConfig struct {
	WebListen               string `yaml:"web_listen"`                   //监听地址
	WebUsername             string `yaml:"web_username"`                 //账号
	WebPassword             string `yaml:"web_password"`                 //密码
	WebLoginFailLimitInHour int    `yaml:"web_login_fail_limit_in_hour"` //每小时最大失败次数

	LogLevel      string `yaml:"log_level"`
	MetricsListen string `yaml:"metrics_listen"` // pprof与prometheus共用的监控监听地址,为空则不开启
}

func parseAppConfigFile(fileName string) (*AppConfig, error) {
	data, err := os.ReadFile(fileName)
	if err != nil {
		return nil, err
	}

	var cfg AppConfig
	if err := yaml.Unmarshal(data, &cfg); err != nil {
		return nil, err
	}
	return &cfg, nil
}

func createAppConfigFile(fileName string) (*AppConfig, error) {
	cfg := AppConfig{
		WebListen:               "0.0.0.0:8080",
		WebUsername:             "admin",
		WebPassword:             "admin",
		WebLoginFailLimitInHour: 10,
		LogLevel:                "info",
		MetricsListen:           "",
	}

	node := &yaml.Node{
		Kind: yaml.MappingNode,
	}

	err := node.Encode(&cfg)
	if err != nil {
		return nil, err
	}
	addComments(node)
	data, err := yaml.Marshal(node)
	if err != nil {
		return nil, err
	}

	os.MkdirAll(path.Dir(fileName), os.ModePerm)

	err = os.WriteFile(fileName, data, 0666)
	if err != nil {
		return nil, err
	}
	return &cfg, nil
}

func addComments(node *yaml.Node) {
	for i := 0; i < len(node.Content); i += 2 {
		key := node.Content[i]

		switch key.Value {
		case "web_listen":
			key.HeadComment = "web监听地址"
		case "web_username":
			key.HeadComment = "web登录账号"
		case "web_password":
			key.HeadComment = "web登录密码"
		case "web_login_fail_limit_in_hour":
			key.HeadComment = "每小时登录失败限制次数"
		case "log_level":
			key.HeadComment = "日志等级:debug/info/warn/error"
		case "metrics_listen":
			key.HeadComment = "监控监听地址(pprof与prometheus共用),为空则不开启"
		}
	}
}

